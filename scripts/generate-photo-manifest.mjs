// Scans /public/images/ for any image file (jpg, png, webp, heic, avif, gif)
// regardless of name, and writes /src/data/imageManifest.js.
//
// Wired into npm scripts:
//   npm run manifest      — regenerate manually
//   npm run dev / build   — runs automatically via predev / prebuild
//
// Drop new photos with ANY filename into /public/images, restart dev,
// and they will appear in the slideshow / sections automatically.

import { readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const imagesDir = join(root, 'public', 'images')
const outDir = join(root, 'src', 'data')
const outFile = join(outDir, 'imageManifest.js')

const EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.heic', '.heif', '.avif', '.gif'])

function listImages() {
  if (!existsSync(imagesDir)) return []
  return readdirSync(imagesDir, { withFileTypes: true })
    .filter((d) => d.isFile())
    .map((d) => d.name)
    .filter((name) => {
      const dot = name.lastIndexOf('.')
      if (dot < 0) return false
      return EXTS.has(name.slice(dot).toLowerCase())
    })
    .sort()
}

const files = listImages()

const banner = `// AUTO-GENERATED — do not edit by hand.
// Regenerated by scripts/generate-photo-manifest.mjs
// Includes every image file in /public/images regardless of name.
`

const body = `export const imageManifest = ${JSON.stringify(files, null, 2)}\n`

if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true })
writeFileSync(outFile, banner + body, 'utf-8')

console.log(`[manifest] wrote ${files.length} images to ${outFile.replace(root, '.')}`)
